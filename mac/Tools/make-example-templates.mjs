// Writes mac/App/TemplatesExamples.swift: the website's examples that have a
// second page ("Built from gates" and the like), and its newer one-page
// examples, as template pages for File > New from Template, from the
// website's own circuits (public/assets/js/sim.js PRESETS), so the two stay
// the same circuit. Places in CedarLogic units (the website's / 16, y up);
// a switch's or a light's name a label beside it; wires by pin name (the
// app routes them itself).
//
//   node mac/Tools/make-example-templates.mjs <cedarlogic-site checkout>
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const site = process.argv[2];
if (!site) { console.error("usage: make-example-templates.mjs <cedarlogic-site>"); process.exit(2); }
const defs = JSON.parse(readFileSync(site + "/public/assets/engine/gatedefs.json", "utf8"));
const ctx = { matchMedia: () => ({ matches: false }), navigator: { platform: "MacIntel", userAgent: "" },
  document: { readyState: "complete", querySelectorAll: () => [] }, URLSearchParams, globalThis: null };
ctx.globalThis = ctx;
vm.runInNewContext(readFileSync(site + "/public/assets/js/sim.js", "utf8"), ctx);
const { PRESETS } = ctx.CedarLogicOnline;

const KEYS = ["d-flip-flop", "jk-flip-flop", "t-flip-flop", "register", "counter-3bit", "adder-4bit", "decoder-2to4", "mux-4to1",
  "comparator-2bit", "parity", "edge-detector", "sr-latch-enable"];
const num = v => { const r = Math.round(v * 1000) / 1000; return Number.isInteger(r) ? r.toFixed(1) : String(r); };
const str = s => JSON.stringify(s);
const NAME = 1.4, NOTE = 1;

function page(pg, name) {
  const parts = [], labels = [], big = {};
  pg.parts.forEach(p => {
    const d = defs.gates[p.type], x = p.x / 16, y = -p.y / 16, angle = (360 - 90 * ((p.r || 0) & 3)) % 360;
    const params = { ...(p.lp || {}) };
    if (p.type === "BB_CLOCK") delete params.MANUAL;   // build's manualClock sets it
    let label = null;
    if (p.type === "AA_LABEL") { label = p.gp.LABEL_TEXT; big[label] = +(p.gp.TEXT_HEIGHT || 2); delete params.LABEL_TEXT; }
    const ps = Object.keys(params).length ? `, params: [${Object.entries(params).map(([k, v]) => `${str(k)}: ${str(String(v))}`).join(", ")}]` : "";
    parts.push(`Part(gate: ${str(p.type)}, x: ${num(x)}, y: ${num(y)}${label ? `, label: ${str(label)}` : ""}${p.on ? ", on: true" : ""}${angle ? `, angle: ${num(angle)}` : ""}${ps})`);
    if (p.label && d.gt === "TOGGLE") {
      big[p.label] = NAME;
      labels.push(angle === 270 ? `Part(gate: "AA_LABEL", x: ${num(x)}, y: ${num(y + 2.6)}, label: ${str(p.label)})`
        : angle === 180 ? `label(${str(p.label)}, x: ${num(x + 2.2)}, y: ${num(y)}, height: ${NAME})`
        : `label(${str(p.label)}, right: ${num(x - 2.2)}, y: ${num(y)}, height: ${NAME})`);
    } else if (p.label) { big[p.label] = NAME; labels.push(`label(${str(p.label)}, x: ${num(x + 2)}, y: ${num(y)}, height: ${NAME})`); }
  });
  const wires = pg.wires.map(([a, b, pin, out = 0]) => {
    const from = pg.parts[a], to = pg.parts[b], fd = defs.gates[from.type];
    const fromPin = fd.o.length ? fd.o[out][0] : fd.i[out][0];
    return `Wire(from: ${a}, fromPin: ${str(fromPin)}, to: ${b}, toPin: ${str(defs.gates[to.type].i[pin][0])})`;
  });
  const bigs = Object.entries(big).map(([k, v]) => `${str(k)}: ${num(v)}`).join(", ");
  return `            ExamplePage(name: ${str(name)},
                        parts: [
                            ${[...parts, ...labels].join(",\n                            ")},
                        ],
                        wires: [
                            ${wires.join(",\n                            ")},
                        ],
                        big: [${bigs || ":"}])`;
}

let out = `// Generated by mac/Tools/make-example-templates.mjs from the website's
// examples (cedarlogic-site public/assets/js/sim.js): don't edit by hand,
// change the website's circuit and run it again. Each example's pages, as
// the website has them (CedarLogic units, y up; names as labels beside
// their switches and lights). Templates.swift builds them.

extension Templates {
    static let websiteExamples: [String: [ExamplePage]] = [
`;
for (const k of KEYS) {
  const pr = PRESETS[k];
  if (!pr) throw new Error("no example " + k);
  const pages = pr.pages || [{ ...pr, name: "" }];
  out += `        ${str(k)}: [\n${pages.map(pg => page(pg, pg.name || "")).join(",\n")},\n        ],\n`;
}
out += `    ]\n}\n`;
writeFileSync(new URL("../App/TemplatesExamples.swift", import.meta.url), out);
console.log("wrote mac/App/TemplatesExamples.swift:", KEYS.length, "examples");
